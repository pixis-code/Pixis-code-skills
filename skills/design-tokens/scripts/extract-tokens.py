#!/usr/bin/env python3
"""Extract named color/spacing CSS variables from existing style sources.

Extraction only. Does not invent token names, does not wire Tailwind, and
does not silently overwrite an existing theme file. Large files are streamed
with a per-file byte cap; incompleteness is reported honestly.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tempfile
from collections import OrderedDict
from pathlib import Path

DEFAULT_MAX_BYTES = 2_000_000
CHUNK_SIZE = 64 * 1024
OVERLAP = 256

GENERATED_MARKER = "Generated by design-tokens/scripts/extract-tokens.py"

COLOR_RE = re.compile(
    r"(?:"
    r"#[0-9a-fA-F]{3,8}\b"
    r"|rgba?\(\s*[^)]+\)"
    r"|hsla?\(\s*[^)]+\)"
    r"|oklch\(\s*[^)]+\)"
    r"|oklab\(\s*[^)]+\)"
    r")"
)
VAR_COLOR_RE = re.compile(
    r"--([a-zA-Z0-9_-]*(?:color|colour|bg|background|fill|stroke|border)[a-zA-Z0-9_-]*)\s*:\s*([^;]+);",
    re.I,
)
VAR_SPACE_RE = re.compile(
    r"--([a-zA-Z0-9_-]*(?:space|spacing|gap|pad|padding|margin|inset|size|radius|rounded)[a-zA-Z0-9_-]*)\s*:\s*([^;]+);",
    re.I,
)
# No trailing \b — `%` is non-word, so \b would drop `100%`.
SPACE_VALUE_RE = re.compile(
    r"(?:^|[\s:,=\(\{])(\d+(?:\.\d+)?(?:px|rem|em|%|vh|vw))(?=$|[\s;,\)\}])"
)

STYLE_GLOBS = (
    "**/*.css",
    "**/*.scss",
    "**/*.sass",
    "**/*.less",
    "**/tailwind.config.js",
    "**/tailwind.config.cjs",
    "**/tailwind.config.mjs",
    "**/tailwind.config.ts",
)

SKIP_PARTS = {
    "node_modules",
    ".git",
    "dist",
    "build",
    ".next",
    "coverage",
    "vendor",
    "__pycache__",
    ".turbo",
    ".vercel",
}

GENERATED_NAME_HINTS = (
    "theme.tokens.css",
    "tokens.extracted.css",
)


def should_skip(path: Path) -> bool:
    return any(part in SKIP_PARTS for part in path.parts)


def is_generated_theme(path: Path) -> bool:
    name = path.name.lower()
    if name in GENERATED_NAME_HINTS or name.endswith(".tokens.css"):
        return True
    try:
        head = path.read_text(encoding="utf-8", errors="replace")[:500]
    except OSError:
        return False
    return GENERATED_MARKER in head


def detect_tailwind_version(root: Path) -> str | None:
    pkg = root / "package.json"
    if pkg.is_file():
        try:
            data = json.loads(pkg.read_text(encoding="utf-8", errors="replace"))
        except json.JSONDecodeError:
            data = {}
        for section in ("dependencies", "devDependencies", "peerDependencies"):
            ver = (data.get(section) or {}).get("tailwindcss")
            if ver:
                cleaned = re.sub(r"^[\^~>=<\s]+", "", str(ver))
                major = cleaned.split(".")[0]
                if major.isdigit():
                    return f"v{major}"
    for css in root.rglob("*.css"):
        if should_skip(css) or is_generated_theme(css):
            continue
        try:
            head = css.read_text(encoding="utf-8", errors="replace")[:4000]
        except OSError:
            continue
        if '@import "tailwindcss"' in head or "@import 'tailwindcss'" in head:
            return "v4"
        if "@tailwind base" in head or "@tailwind utilities" in head:
            return "v3"
    if any(
        (root / name).exists()
        for name in (
            "tailwind.config.js",
            "tailwind.config.cjs",
            "tailwind.config.mjs",
            "tailwind.config.ts",
        )
    ):
        return "v3"
    return None


def discover_sources(root: Path, exclude: set[Path]) -> list[Path]:
    found: list[Path] = []
    seen: set[Path] = set()
    exclude_resolved = {p.resolve() for p in exclude}
    for pattern in STYLE_GLOBS:
        for path in root.glob(pattern):
            if not path.is_file() or should_skip(path):
                continue
            resolved = path.resolve()
            if resolved in seen or resolved in exclude_resolved:
                continue
            if is_generated_theme(path):
                continue
            seen.add(resolved)
            found.append(path)
    return sorted(found, key=lambda p: str(p))


def normalize_var_name(name: str) -> str:
    return name if name.startswith("--") else f"--{name}"


def scan_text(
    text: str,
    colors: OrderedDict[str, str],
    spacing: OrderedDict[str, str],
    unnamed_colors: OrderedDict[str, str],
    unnamed_spacing: OrderedDict[str, str],
) -> None:
    for m in VAR_COLOR_RE.finditer(text):
        colors.setdefault(normalize_var_name(m.group(1)), m.group(2).strip())
    for m in VAR_SPACE_RE.finditer(text):
        spacing.setdefault(normalize_var_name(m.group(1)), m.group(2).strip())
    named_values = set(colors.values()) | set(spacing.values())
    for m in COLOR_RE.finditer(text):
        val = m.group(0)
        if val not in named_values:
            unnamed_colors.setdefault(val, val)
    for m in SPACE_VALUE_RE.finditer(text):
        val = m.group(1)
        if val in {"0", "0px", "0rem"}:
            continue
        if val not in named_values:
            unnamed_spacing.setdefault(val, val)


def scan_file(
    path: Path,
    max_bytes: int,
    colors: OrderedDict[str, str],
    spacing: OrderedDict[str, str],
    unnamed_colors: OrderedDict[str, str],
    unnamed_spacing: OrderedDict[str, str],
) -> dict:
    meta = {
        "path": str(path),
        "bytes_read": 0,
        "complete": True,
        "error": None,
    }
    try:
        size = path.stat().st_size
    except OSError as exc:
        meta["complete"] = False
        meta["error"] = str(exc)
        return meta

    try:
        with path.open("rb") as fh:
            leftover = b""
            budget = max_bytes
            while budget > 0:
                chunk = fh.read(min(CHUNK_SIZE, budget))
                if not chunk:
                    break
                meta["bytes_read"] += len(chunk)
                budget -= len(chunk)
                data = leftover + chunk
                if len(data) > OVERLAP and budget > 0:
                    process, leftover = data[:-OVERLAP], data[-OVERLAP:]
                else:
                    process, leftover = data, b""
                scan_text(
                    process.decode("utf-8", errors="replace"),
                    colors,
                    spacing,
                    unnamed_colors,
                    unnamed_spacing,
                )
            if leftover and budget > 0:
                scan_text(
                    leftover.decode("utf-8", errors="replace"),
                    colors,
                    spacing,
                    unnamed_colors,
                    unnamed_spacing,
                )
            if meta["bytes_read"] < size:
                meta["complete"] = False
                meta["error"] = (
                    f"stopped after {meta['bytes_read']} bytes "
                    f"(file size {size}); partial tokens kept"
                )
    except OSError as exc:
        meta["complete"] = False
        meta["error"] = str(exc)
    return meta


def build_theme_css(colors: OrderedDict[str, str], spacing: OrderedDict[str, str]) -> str:
    """Named source variables only. No @theme block — integration is separate."""
    lines = [
        f"/* {GENERATED_MARKER} */",
        "/* Extraction only: named variables from existing sources. */",
        "/* Unnamed literals are listed in the JSON summary for review. */",
        "/* Tailwind wiring is NOT done here — see SKILL.md Job A integration. */",
        ":root {",
    ]
    for name, value in colors.items():
        lines.append(f"  {name}: {value};")
    for name, value in spacing.items():
        lines.append(f"  {name}: {value};")
    lines.append("}")
    lines.append("")
    return "\n".join(lines) + "\n"


def defined_custom_props(css: str) -> set[str]:
    return set(re.findall(r"(--[a-zA-Z0-9_-]+)\s*:", css))


def unresolved_var_refs(css: str) -> list[str]:
    defined = defined_custom_props(css)
    refs = re.findall(r"var\((--[a-zA-Z0-9_-]+)\)", css)
    return sorted({ref for ref in refs if ref not in defined})


def run_extract(
    root: Path,
    out: Path,
    json_out: Path | None,
    max_bytes: int,
    force: bool,
) -> tuple[int, dict]:
    if not root.is_dir():
        print(f"error: root is not a directory: {root}", file=sys.stderr)
        return 2, {}

    if out.exists() and not force:
        print(
            f"error: theme file already exists: {out}\n"
            "Refusing to overwrite. Pass --force only after inspecting the file, "
            "or choose a different --out path. Existing Tailwind/CSS config is never modified.",
            file=sys.stderr,
        )
        return 3, {"theme_file": str(out), "refused_overwrite": True}

    exclude = {out}
    sources = discover_sources(root, exclude=exclude)
    tw = detect_tailwind_version(root)

    colors: OrderedDict[str, str] = OrderedDict()
    spacing: OrderedDict[str, str] = OrderedDict()
    unnamed_colors: OrderedDict[str, str] = OrderedDict()
    unnamed_spacing: OrderedDict[str, str] = OrderedDict()
    file_reports: list[dict] = []

    if not sources:
        summary = {
            "root": str(root),
            "theme_file": None,
            "tailwind_version": tw,
            "sources_scanned": 0,
            "incomplete_files": [],
            "complete": False,
            "success": False,
            "error": "no usable style sources found",
            "colors_named": 0,
            "spacing_named": 0,
            "unnamed_colors": [],
            "unnamed_spacing": [],
            "files": [],
            "note": (
                "Tailwind config JS/TS color and spacing object keys are not "
                "auto-parsed as named tokens; review those files manually."
            ),
        }
        print(json.dumps(summary, indent=2))
        if json_out:
            json_out.parent.mkdir(parents=True, exist_ok=True)
            json_out.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
        print("error: no usable style sources found; no theme file written", file=sys.stderr)
        return 1, summary

    for path in sources:
        report = scan_file(
            path, max_bytes, colors, spacing, unnamed_colors, unnamed_spacing
        )
        file_reports.append(report)
        if not report["complete"]:
            print(f"incomplete: {report['path']}: {report['error']}", file=sys.stderr)

    if not colors and not spacing:
        summary = {
            "root": str(root),
            "theme_file": None,
            "tailwind_version": tw,
            "sources_scanned": len(file_reports),
            "incomplete_files": [r for r in file_reports if not r["complete"]],
            "complete": False,
            "success": False,
            "error": "no named color/spacing CSS variables found",
            "colors_named": 0,
            "spacing_named": 0,
            "unnamed_colors": list(unnamed_colors.keys()),
            "unnamed_spacing": list(unnamed_spacing.keys()),
            "files": file_reports,
            "note": (
                "Unnamed literals need manual review. Tailwind config object "
                "maps are not auto-parsed; review them manually."
            ),
        }
        print(json.dumps({
            k: summary[k]
            for k in (
                "theme_file",
                "tailwind_version",
                "sources_scanned",
                "complete",
                "success",
                "error",
                "unnamed_colors",
                "unnamed_spacing",
                "incomplete_files",
                "note",
            )
        }, indent=2))
        if json_out:
            json_out.parent.mkdir(parents=True, exist_ok=True)
            json_out.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
        print(
            "error: no named tokens found; no theme file written. "
            "See unnamed_* in the summary for review.",
            file=sys.stderr,
        )
        return 1, summary

    css = build_theme_css(colors, spacing)
    broken = unresolved_var_refs(css)
    if broken:
        print(
            f"error: unresolved var() references in generated CSS: {broken}",
            file=sys.stderr,
        )
        return 4, {"unresolved": broken}

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(css, encoding="utf-8")

    incomplete_files = [r for r in file_reports if not r["complete"]]
    summary = {
        "root": str(root),
        "theme_file": str(out),
        "tailwind_version": tw,
        "sources_scanned": len(file_reports),
        "source_paths": [r["path"] for r in file_reports],
        "incomplete_files": incomplete_files,
        "complete": len(incomplete_files) == 0,
        "success": True,
        "colors_named": len(colors),
        "spacing_named": len(spacing),
        "unnamed_colors": list(unnamed_colors.keys()),
        "unnamed_spacing": list(unnamed_spacing.keys()),
        "unresolved_var_refs": broken,
        "files": file_reports,
        "integration": "not_applied",
        "note": (
            "Wrote named CSS variables only. Did not modify Tailwind config or "
            "append @theme. Wire variables in a separate integration step. "
            "Tailwind config JS/TS object maps are not auto-parsed as named "
            "tokens; review them manually. Unnamed literals are for review only."
        ),
    }

    if json_out:
        json_out.parent.mkdir(parents=True, exist_ok=True)
        json_out.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")

    print(json.dumps({
        k: summary[k]
        for k in (
            "theme_file",
            "tailwind_version",
            "sources_scanned",
            "complete",
            "success",
            "colors_named",
            "spacing_named",
            "unnamed_colors",
            "unnamed_spacing",
            "unresolved_var_refs",
            "incomplete_files",
            "integration",
            "note",
        )
    }, indent=2))
    return 0, summary


def run_self_tests() -> int:
    """Focused regression tests. Exit 0 only if all pass."""
    results: list[tuple[str, bool, str]] = []
    script = Path(__file__).resolve()

    def record(name: str, ok: bool, detail: str) -> None:
        results.append((name, ok, detail))
        print(f"{'PASS' if ok else 'FAIL'}: {name} — {detail}")

    # --- v4-named vars / no broken refs / no @theme ---
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        (root / "src").mkdir()
        (root / "src" / "a.css").write_text(
            ":root { --bg-surface: #ff0000; --color-primary: #00ff00; --space-md: 8px; }\n",
            encoding="utf-8",
        )
        (root / "package.json").write_text(
            '{"devDependencies":{"tailwindcss":"^4.0.0"}}', encoding="utf-8"
        )
        out = root / "theme.tokens.css"
        code, summary = run_extract(root, out, root / "s.json", DEFAULT_MAX_BYTES, force=False)
        css = out.read_text(encoding="utf-8") if out.exists() else ""
        broken = unresolved_var_refs(css)
        ok = (
            code == 0
            and "--bg-surface:" in css
            and "--color-primary:" in css
            and "@theme" not in css
            and not broken
            and summary.get("tailwind_version") == "v4"
        )
        record(
            "v4 named vars + no unresolved var() + no @theme",
            ok,
            f"exit={code} broken={broken} has_bg={('--bg-surface:' in css)}",
        )

    # --- v3: no @theme, config untouched ---
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        cfg = root / "tailwind.config.js"
        cfg.write_text(
            "module.exports = { theme: { extend: { colors: { brand: '#123456' } } } }\n",
            encoding="utf-8",
        )
        before = cfg.read_text(encoding="utf-8")
        (root / "a.css").write_text(
            ":root { --color-brand: #123456; --space-md: 16px; }\n", encoding="utf-8"
        )
        (root / "package.json").write_text(
            '{"devDependencies":{"tailwindcss":"^3.4.0"}}', encoding="utf-8"
        )
        out = root / "theme.tokens.css"
        code, summary = run_extract(root, out, None, DEFAULT_MAX_BYTES, force=False)
        css = out.read_text(encoding="utf-8")
        ok = (
            code == 0
            and "@theme" not in css
            and cfg.read_text(encoding="utf-8") == before
            and summary.get("tailwind_version") == "v3"
            and summary.get("integration") == "not_applied"
        )
        record("v3 no @theme + tailwind.config preserved", ok, f"exit={code}")

    # --- refuse overwrite ---
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        (root / "a.css").write_text(":root { --color-a: #111111; }\n", encoding="utf-8")
        out = root / "theme.tokens.css"
        out.write_text("/* existing */\n:root { --keep: 1; }\n", encoding="utf-8")
        before = out.read_text(encoding="utf-8")
        code, _ = run_extract(root, out, None, DEFAULT_MAX_BYTES, force=False)
        ok = code == 3 and out.read_text(encoding="utf-8") == before
        record("refuse overwrite without --force", ok, f"exit={code}")

    # --- no duplicate @theme (extraction never emits @theme) ---
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        (root / "a.css").write_text(
            '@import "tailwindcss";\n@theme { --color-x: #000; }\n'
            ":root { --color-primary: #00ff00; }\n",
            encoding="utf-8",
        )
        (root / "package.json").write_text(
            '{"devDependencies":{"tailwindcss":"^4.0.0"}}', encoding="utf-8"
        )
        out = root / "theme.tokens.css"
        code, _ = run_extract(root, out, None, DEFAULT_MAX_BYTES, force=False)
        css = out.read_text(encoding="utf-8")
        ok = code == 0 and css.count("@theme") == 0
        record("no @theme appended to extracted theme", ok, f"@theme_count={css.count('@theme')}")

    # --- second run excludes generated output ---
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        (root / "a.css").write_text(
            ":root { --color-primary: #112233; --space-md: 16px; }\n", encoding="utf-8"
        )
        out = root / "theme.tokens.css"
        code1, s1 = run_extract(root, out, root / "s1.json", DEFAULT_MAX_BYTES, force=False)
        code2, s2 = run_extract(root, out, root / "s2.json", DEFAULT_MAX_BYTES, force=True)
        paths2 = s2.get("source_paths") or []
        included = any(Path(p).resolve() == out.resolve() for p in paths2)
        ok = code1 == 0 and code2 == 0 and not included and s2.get("sources_scanned") == 1
        record(
            "second run excludes generated output",
            ok,
            f"sources={s2.get('sources_scanned')} included_out={included}",
        )

    # --- percentage dimensions: named kept; distinct % reported unnamed ---
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        (root / "a.css").write_text(
            ":root { --space-full: 100%; }\n"
            ".x { width: 50%; margin: 24px; color: #abcdef; }\n",
            encoding="utf-8",
        )
        out = root / "theme.tokens.css"
        code, summary = run_extract(root, out, root / "s.json", DEFAULT_MAX_BYTES, force=False)
        css = out.read_text(encoding="utf-8")
        ok = (
            code == 0
            and "--space-full: 100%;" in css
            and "50%" in summary.get("unnamed_spacing", [])
            and "#abcdef" in summary.get("unnamed_colors", [])
            and "--swatch-" not in css
            and "--space-24px" not in css
            and "--space-14px" not in css
            and "--space-50" not in css
        )
        record(
            "percentage + unnamed reported, no invented names",
            ok,
            f"unnamed_spacing={summary.get('unnamed_spacing')} css_has_swatch={'--swatch-' in css}",
        )

    # --- invented names must not appear ---
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        (root / "a.css").write_text(
            ".x { font-size: 14px; color: #abc; padding: 24px; }\n"
            ":root { --color-primary: #112233; }\n",
            encoding="utf-8",
        )
        out = root / "theme.tokens.css"
        code, summary = run_extract(root, out, None, DEFAULT_MAX_BYTES, force=False)
        css = out.read_text(encoding="utf-8")
        bad = ["--space-14px", "--swatch-", "--space-24px"]
        ok = code == 0 and all(b not in css for b in bad) and "--color-primary:" in css
        record("no invented token names from font-size/hex", ok, f"bad_in_css={[b for b in bad if b in css]}")

    # --- empty project ---
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        out = root / "theme.tokens.css"
        code, summary = run_extract(root, out, root / "s.json", DEFAULT_MAX_BYTES, force=False)
        ok = code == 1 and not out.exists() and summary.get("success") is False
        record("empty project: no theme written, non-zero exit", ok, f"exit={code} exists={out.exists()}")

    # --- only unnamed literals ---
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        (root / "a.css").write_text(".x { color: #ff00ff; margin: 12px; }\n", encoding="utf-8")
        out = root / "theme.tokens.css"
        code, summary = run_extract(root, out, None, DEFAULT_MAX_BYTES, force=False)
        ok = (
            code == 1
            and not out.exists()
            and "#ff00ff" in summary.get("unnamed_colors", [])
            and "12px" in summary.get("unnamed_spacing", [])
        )
        record("unnamed-only: no theme, listed for review", ok, f"exit={code}")

    # --- truncation ---
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        (root / "ok.css").write_text(":root { --color-ok: #010203; }\n", encoding="utf-8")
        huge = root / "huge.css"
        huge.write_text(
            ":root { --color-early: #010101; }\n"
            + ("z" * 4000)
            + "\n:root { --color-late: #eeeeee; --space-late: 99px; }\n",
            encoding="utf-8",
        )
        out = root / "theme.tokens.css"
        code, summary = run_extract(root, out, None, 1500, force=False)
        css = out.read_text(encoding="utf-8")
        ok = (
            code == 0
            and summary.get("complete") is False
            and "--color-early:" in css
            and "--color-ok:" in css
            and "--color-late:" not in css
            and any(f.get("bytes_read") == 1500 for f in summary.get("incomplete_files", []))
        )
        record("truncation accurate + continues other files", ok, f"complete={summary.get('complete')}")

    # --- unreadable file ---
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        good = root / "good.css"
        good.write_text(":root { --color-x: #abcabc; }\n", encoding="utf-8")
        bad = root / "bad.css"
        bad.write_text(":root { --color-y: #000000; }\n", encoding="utf-8")
        bad.chmod(0)
        out = root / "theme.tokens.css"
        try:
            code, summary = run_extract(root, out, None, DEFAULT_MAX_BYTES, force=False)
            css = out.read_text(encoding="utf-8") if out.exists() else ""
            incomplete = summary.get("incomplete_files") or []
            ok = code == 0 and "--color-x:" in css and len(incomplete) >= 1
            record("unreadable file reported, other sources continue", ok, f"exit={code} incomplete={len(incomplete)}")
        finally:
            bad.chmod(0o644)

    failed = [name for name, ok, _ in results if not ok]
    print(f"\n{len(results) - len(failed)}/{len(results)} passed")
    return 1 if failed else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help="Theme CSS path (default: <root>/theme.tokens.css)",
    )
    parser.add_argument("--json-out", type=Path, default=None)
    parser.add_argument("--max-bytes", type=int, default=DEFAULT_MAX_BYTES)
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite --out only after you have inspected the existing file",
    )
    parser.add_argument(
        "--self-test",
        action="store_true",
        help="Run built-in regression tests and exit",
    )
    args = parser.parse_args(argv)

    if args.self_test:
        return run_self_tests()

    root = args.root.resolve()
    out = (args.out or (root / "theme.tokens.css")).resolve()
    json_out = args.json_out.resolve() if args.json_out else None
    code, _ = run_extract(root, out, json_out, args.max_bytes, args.force)
    return code


if __name__ == "__main__":
    sys.exit(main())
